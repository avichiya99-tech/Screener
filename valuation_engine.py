FINANCIAL_SECTORS = {"Financial Services", "Banks", "Insurance"}
CYCLICAL_SECTORS = {"Basic Materials", "Energy"}
EXPLICIT_YEARS = 10  # years 1-5 at the growth driver, years 6-10 fade linearly to terminal growth
ER_PERSISTENCE = 0.7  # share of a bank's excess-return spread that survives each year after Year 5


class Inputs:
    """Records every model input with where it came from: reported, estimated, or default."""

    STATUSES = ("reported", "estimated", "default")

    def __init__(self):
        self._items: dict[str, dict] = {}

    def set(self, name: str, value, status: str):
        if status not in self.STATUSES:
            raise ValueError(f"bad status {status!r}")
        self._items[name] = {"value": None if value is None else float(value), "status": status}
        return value

    def as_dict(self) -> dict:
        return {k: dict(v) for k, v in self._items.items()}


def _bounded(raw, lo: float, hi: float, default: float) -> tuple[float, str]:
    """Clip a raw input. Missing -> (default, 'default'); clipped -> 'estimated'; else 'reported'."""
    if raw is None or (isinstance(raw, float) and np.isnan(raw)):
        return float(default), "default"
    val = float(np.clip(raw, lo, hi))
    return val, ("reported" if val == float(raw) else "estimated")


def get_row_value(df: pd.DataFrame | None, labels: list[str], default: float = 0.0) -> float:
    """Safely extracts the most recent non-null numeric value matching any label."""
    if df is None or df.empty:
        return default
    for label in labels:
        if label in df.index:
            series = pd.to_numeric(df.loc[label], errors="coerce").dropna()
            if not series.empty:
                return float(series.iloc[0])
    return default


def historical_growth(df: pd.DataFrame | None, labels: list[str], default: float = 0.08) -> tuple[float, int, str]:
    """Median year-on-year growth (robust to one bad year), clipped to [-5%, 25%].

    Returns (growth, years_of_history, status). Status: 'reported' with >= 3 YoY points,
    'estimated' with 1-2 points or when clipped, 'default' when no usable history.
    """
    if df is None or df.empty:
        return float(default), 0, "default"
    for label in labels:
        if label in df.index:
            series = pd.to_numeric(df.loc[label], errors="coerce").dropna()  # newest first
            vals = series.tolist()
            yoy = [vals[i] / vals[i + 1] - 1 for i in range(len(vals) - 1) if vals[i] > 0 and vals[i + 1] > 0]
            if not yoy:
                return float(default), len(vals), "default"
            raw = float(np.median(yoy))
            g = float(np.clip(raw, -0.05, 0.25))
            status = "reported" if (len(yoy) >= 3 and g == raw) else "estimated"
            return g, len(vals), status
    return float(default), 0, "default"


def build_historical_eps_div_df(bundle: dict) -> pd.DataFrame:
    """Builds a 5-year historical table of Annual EPS, Annual DPS, and Payout Ratio."""
    inc = bundle.get("income")
    divs = bundle.get("dividends")

    eps_by_year = {}
    if inc is not None and not inc.empty:
        for lbl in ["Diluted EPS", "Basic EPS"]:
            if lbl in inc.index:
                for dt, val in pd.to_numeric(inc.loc[lbl], errors="coerce").dropna().items():
                    eps_by_year[pd.to_datetime(dt).year] = float(val)
                break

    div_by_year = {}
    if divs is not None and len(divs) > 0:
        s = divs.copy()
        s.index = pd.to_datetime(s.index)
        if getattr(s.index, "tz", None) is not None:
            s.index = s.index.tz_localize(None)
        for yr, val in s.groupby(s.index.year).sum().items():
            div_by_year[int(yr)] = float(val)

    all_years = sorted(set(eps_by_year.keys()) | set(div_by_year.keys()))
    recent_years = all_years[-5:] if len(all_years) > 5 else all_years

    rows = []
    for yr in recent_years:
        eps = eps_by_year.get(yr)
        dps = div_by_year.get(yr, 0.0)
        payout = (dps / eps * 100) if (eps is not None and eps > 0) else None
        rows.append({
            "Year": str(yr),
            "EPS": round(eps, 2) if eps is not None else None,
            "Annual DPS": round(dps, 2),
            "Payout Ratio (%)": round(payout, 1) if payout is not None else None,
        })
    return pd.DataFrame(rows)


def compute_dividend_quality(bundle: dict, val_res: dict) -> dict:
    """India-specific 0-100 Dividend Quality Score (Compounder vs. Yield Trap Risk)."""
    info = bundle.get("info") or {}
    price = info.get("currentPrice") or info.get("regularMarketPrice") or 0.0
    dps = info.get("dividendRate") or 0.0
    t_eps = info.get("trailingEps") or 0.0
    div_yield = (dps / price * 100) if (price > 0 and dps > 0) else 0.0

    if dps <= 0:
        return {
            "score": None,
            "badge": "No Dividend",
            "div_cagr_5y": None,
            "consistency_yrs": 0,
            "flags": [],
        }

    is_fin = val_res.get("is_financial", False)
    hist_df = build_historical_eps_div_df(bundle)
    flags = []

    # 1. 5-Year Dividend Consistency (30 pts)
    consistency_pts = 15
    div_cagr = None
    consistent_steps = 0
    if not hist_df.empty and "Annual DPS" in hist_df.columns:
        dps_vals = hist_df["Annual DPS"].dropna().tolist()
        paid_years = sum(1 for v in dps_vals if v > 0)
        if len(dps_vals) >= 2:
            cuts = 0
            for i in range(1, len(dps_vals)):
                if dps_vals[i] >= dps_vals[i - 1] * 0.98 and dps_vals[i] > 0:
                    consistent_steps += 1
                elif dps_vals[i - 1] > 0:
                    cuts += 1
            if paid_years >= min(4, len(dps_vals)) and cuts == 0:
                consistency_pts = 30
            elif paid_years >= 3 and cuts <= 1:
                consistency_pts = 20
            else:
                consistency_pts = 6
                flags.append("Inconsistent Div")

            if dps_vals[0] > 0 and dps_vals[-1] > 0:
                div_cagr = ((dps_vals[-1] / dps_vals[0]) ** (1 / (len(dps_vals) - 1)) - 1) * 100

    # 2. Cash Flow / Earnings Coverage (30 pts)
    coverage_pts = 15
    if is_fin:
        roe = info.get("returnOnEquity") or 0.12
        payout_eps = (dps / t_eps * 100) if t_eps > 0 else 999
        if roe >= 0.14 and payout_eps <= 45:
            coverage_pts = 28
        elif roe >= 0.10 and payout_eps <= 65:
            coverage_pts = 20
        else:
            coverage_pts = 8
    else:
        fcf_ttm = val_res.get("fcf_ttm", 0.0)
        divs_paid = val_res.get("dividends_paid", 0.0)
        if fcf_ttm <= 0:
            coverage_pts = 0
            flags.append("Negative FCF")
        elif divs_paid > 0:
            fcf_payout = (divs_paid / fcf_ttm) * 100
            if fcf_payout <= 50:
                coverage_pts = 30
            elif fcf_payout <= 75:
                coverage_pts = 22
            elif fcf_payout <= 100:
                coverage_pts = 12
            else:
                coverage_pts = 0
                flags.append("Div > FCF")
        else:
            coverage_pts = 20

    # 3. EPS Payout Sustainability (20 pts)
    if t_eps <= 0:
        payout_pts = 0
        flags.append("Negative EPS")
    else:
        payout_pct = (dps / t_eps) * 100
        if payout_pct <= 60:
            payout_pts = 20
        elif payout_pct <= 80:
            payout_pts = 12
        else:
            payout_pts = 4
            flags.append("High Payout (>80%)")

    # 4. Balance Sheet Safety & Dividend Growth (20 pts)
    growth_pts = 5
    if div_cagr is not None:
        if div_cagr >= 8:
            growth_pts = 10
        elif div_cagr >= 3:
            growth_pts = 6
        elif div_cagr >= 0:
            growth_pts = 3
        else:
            growth_pts = 0

    if is_fin:
        bs_pts = 6  # neutral: net debt / EBITDA is not meaningful for lenders
    else:
        net_debt = val_res.get("total_debt", 0.0) - val_res.get("cash", 0.0)
        ebitda = val_res.get("ebitda_ttm", 0.0)
        if net_debt <= 0:
            bs_pts = 10
        elif ebitda > 0:
            nd_ebitda = net_debt / ebitda
            if nd_ebitda < 1.0:
                bs_pts = 10
            elif nd_ebitda < 2.5:
                bs_pts = 6
            else:
                bs_pts = 2
                flags.append("High Leverage")
        else:
            bs_pts = 4

    total_score = int(np.clip(consistency_pts + coverage_pts + payout_pts + growth_pts + bs_pts, 0, 100))

    if ("Div > FCF" in flags or "Negative FCF" in flags) and div_yield >= 3.0 and total_score < 50:
        badge = "Yield Trap Risk"
    elif total_score >= 75:
        badge = "Compounder"
    elif total_score >= 55:
        badge = "Stable Payer"
    elif total_score >= 35:
        badge = "Watchlist"
    else:
        badge = "Yield Trap Risk"

    return {
        "score": total_score,
        "badge": badge,
        "div_cagr_5y": round(div_cagr, 1) if div_cagr is not None else None,
        "consistency_yrs": consistent_steps,
        "flags": flags,
    }


def compute_valuation(
    bundle: dict,
    rf: float = 0.07,
    erp: float = 0.055,
    terminal_g: float = 0.05,
    driver_override: float | None = None,
    discount_override: float | None = None,
    mos_pct: float = 0.25,
    margin_override: float | None = None,
) -> dict:
    """
    Sector-aware valuation engine:
    - Non-Financials: 5-Year FCFF DCF (driver = 5Y Revenue Growth Rate, discount = WACC)
    - Banks / NBFCs / Insurance: 5-Year Residual Income / Excess Return Model (driver = Expected ROE, discount = Ke)
    """
    info = bundle.get("info") or {}
    inc = bundle.get("income")
    bal = bundle.get("balance")
    cf = bundle.get("cashflow")

    sector = info.get("sector", "Unknown")
    is_fin = sector in FINANCIAL_SECTORS

    price = info.get("currentPrice") or info.get("regularMarketPrice")
    shares = info.get("sharesOutstanding")
    mcap = info.get("marketCap") or (price * shares if price and shares else None)

    if not all([price, shares, mcap]) or price <= 0 or shares <= 0:
        return {"valid": False, "is_financial": is_fin, "reason": "Missing price or shares data"}

    inputs = Inputs()
    beta, beta_status = _bounded(info.get("beta"), 0.4, 2.2, 1.0)
    inputs.set("beta", beta, beta_status)
    ke = rf + beta * erp

    # =====================================================================
    # MODEL A: RESIDUAL INCOME (EXCESS RETURN) MODEL FOR BANKS & NBFCs
    # =====================================================================
    if is_fin:
        bvps = info.get("bookValue")
        bvps_status = "reported"
        if not bvps or bvps <= 0:
            eq = get_row_value(bal, ["Stockholders Equity", "Total Equity Gross Minority Interest", "Common Stock Equity"])
            bvps = (eq / shares) if eq > 0 else 0.0
            bvps_status = "estimated"
        if bvps <= 0:
            return {"valid": False, "is_financial": True, "sector": sector, "reason": "Missing positive Book Value per Share"}
        inputs.set("bvps", bvps, bvps_status)

        raw_roe = info.get("returnOnEquity")
        roe_source = "reported"
        if raw_roe is None:
            ni = get_row_value(inc, ["Net Income", "Net Income Common Stockholders"])
            raw_roe = (ni / (bvps * shares)) if (ni and bvps > 0) else None
            roe_source = "estimated"
        fin_years = 0
        if inc is not None and not inc.empty:
            for lbl in ("Net Income", "Net Income Common Stockholders"):
                if lbl in inc.index:
                    fin_years = int(pd.to_numeric(inc.loc[lbl], errors="coerce").notna().sum())
                    break
        fin_reason = None
        if raw_roe is not None and raw_roe <= 0:
            fin_reason = "Loss-making: valuation not meaningful"
        elif fin_years < 3:
            fin_reason = "Less than 3 years of history"
        hist_roe, roe_status = _bounded(raw_roe, 0.04, 0.30, 0.14)
        if roe_status == "reported":
            roe_status = roe_source
        inputs.set("roe", hist_roe, roe_status)
        roe = driver_override if driver_override is not None else hist_roe

        dps = info.get("dividendRate") or 0.0
        t_eps = info.get("trailingEps") or (bvps * hist_roe)
        if dps <= 0 and "dividendRate" in info:
            raw_payout = 0.0  # a reported zero dividend is real data, not a missing value
        else:
            raw_payout = (dps / t_eps) if (t_eps and t_eps > 0 and dps > 0) else None
        payout, payout_status = _bounded(raw_payout, 0.0, 0.70, 0.15)
        inputs.set("payout", payout, payout_status)

        disc = discount_override if discount_override is not None else ke
        if disc <= terminal_g:
            return {"valid": False, "is_financial": True, "reason": "Cost of Equity must exceed Terminal Growth"}

        rows = []
        curr_bv = bvps
        pv_er_total = 0.0
        for yr in range(1, 6):
            eps_proj = curr_bv * roe
            dps_proj = eps_proj * payout
            excess_ret = curr_bv * (roe - disc)
            pv_er = excess_ret / ((1 + disc) ** yr)
            pv_er_total += pv_er
            end_bv = curr_bv + (eps_proj - dps_proj)
            rows.append({
                "Year": f"Year {yr}",
                "Begin BVPS": curr_bv,
                "Projected EPS": eps_proj,
                "Projected DPS": dps_proj,
                "Excess Return": excess_ret,
                "PV of Excess Return": pv_er,
                "End BVPS": end_bv,
            })
            curr_bv = end_bv

        # Terminal: the excess-return spread fades by ER_PERSISTENCE each year after Year 5
        # (Ohlson persistence), instead of earning a fixed share of it forever.
        term_er = curr_bv * (roe - disc)
        tv_er = term_er / (1 + disc - ER_PERSISTENCE)
        pv_tv_er = tv_er / ((1 + disc) ** 5)

        intrinsic = bvps + pv_er_total + pv_tv_er
        upside = ((intrinsic - price) / price) * 100
        mos_buy = intrinsic * (1 - mos_pct)

        return {
            "valid": True,
            "model": "Excess Return (Fin)",
            "is_financial": True,
            "meaningful": fin_reason is None,
            "not_meaningful_reason": fin_reason,
            "history_years": fin_years,
            "sector": sector,
            "currency": info.get("currency", "INR"),
            "price": price,
            "shares": shares,
            "bvps": bvps,
            "payout_ratio_model": payout,
            "hist_driver": hist_roe,
            "driver": roe,
            "driver_label": "ROE",
            "discount_rate": disc,
            "terminal_g": terminal_g,
            "pv_er_total": pv_er_total,
            "tv_er": tv_er,
            "pv_tv_er": pv_tv_er,
            "terminal_method": f"persistence_{ER_PERSISTENCE}",
            "inputs": inputs.as_dict(),
            "intrinsic_price": intrinsic,
            "mos_buy_price": mos_buy,
            "upside_pct": upside,
            "ebit_margin": roe,
            "fcf_ttm": 0.0,
            "dividends_paid": 0.0,
            "total_debt": 0.0,
            "cash": 0.0,
            "ebitda_ttm": 0.0,
            "projection_df": pd.DataFrame(rows),
        }

    # =====================================================================
    # MODEL B: 5-YEAR FCFF DCF FOR NON-FINANCIALS
    # =====================================================================
    rev = get_row_value(inc, ["Total Revenue", "Operating Revenue"])
    if rev <= 0:
        return {"valid": False, "is_financial": False, "reason": "Missing positive revenue data"}

    ebit = get_row_value(inc, ["EBIT", "Operating Income"])
    tax_p = get_row_value(inc, ["Tax Provision", "Income Tax Expense"])
    pretax = get_row_value(inc, ["Pretax Income"])
    interest = abs(get_row_value(inc, ["Interest Expense", "Interest Expense Non Operating"]))
    da = abs(get_row_value(cf, ["Depreciation And Amortization", "Depreciation"]))
    capex = abs(get_row_value(cf, ["Capital Expenditure", "Purchase Of PPE"]))
    fcf_ttm = get_row_value(cf, ["Free Cash Flow"])
    divs_paid = abs(get_row_value(cf, ["Cash Dividends Paid", "Common Stock Dividend Paid"]))
    debt = get_row_value(bal, ["Total Debt", "Long Term Debt"])
    cash = get_row_value(bal, ["Cash And Cash Equivalents", "Cash Cash Equivalents And Short Term Investments"])

    ebitda_ttm = ebit + da if ebit > 0 else get_row_value(inc, ["EBITDA"])
    tax, tax_status = _bounded((tax_p / pretax) if (pretax > 0 and tax_p) else None, 0.15, 0.35, 0.25)
    inputs.set("tax_rate", tax, tax_status)
    hist_cagr, rev_years, growth_status = historical_growth(inc, ["Total Revenue", "Operating Revenue"], default=0.08)
    inputs.set("revenue_growth", hist_cagr, growth_status)
    rev_g = driver_override if driver_override is not None else hist_cagr

    not_meaningful_reason = None
    if ebit <= 0:
        not_meaningful_reason = "Loss-making: DCF not meaningful"
    elif rev_years < 3:
        not_meaningful_reason = "Less than 3 years of history"
    elif sector in CYCLICAL_SECTORS:
        not_meaningful_reason = "Cyclical: earnings swing with commodity prices"
    ebit_m, ebit_status = _bounded((ebit / rev) if ebit > 0 else None, 0.02, 0.50, 0.12)
    inputs.set("ebit_margin", ebit_m, ebit_status)
    if margin_override is not None:
        ebit_m = margin_override
    da_p, da_status = _bounded((da / rev) if da > 0 else None, 0.01, 0.15, 0.03)
    inputs.set("da_pct", da_p, da_status)
    capex_p, capex_status = _bounded((capex / rev) if capex > 0 else None, 0.01, 0.20, 0.05)
    inputs.set("capex_pct", capex_p, capex_status)
    nwc_p = 0.01

    kd = float(np.clip((interest / debt) if debt > 0 else (rf + 0.015), rf, rf + 0.06)) * (1 - tax)
    wacc_calc = (mcap / (mcap + debt)) * ke + (debt / (mcap + debt)) * kd
    wacc = discount_override if discount_override is not None else wacc_calc

    if wacc <= terminal_g:
        return {"valid": False, "is_financial": False, "reason": "WACC must exceed Terminal Growth"}

    rows = []
    crev = rev
    pv_tot = 0.0
    for yr in range(1, EXPLICIT_YEARS + 1):
        g_yr = rev_g if yr <= 5 else rev_g + (terminal_g - rev_g) * (yr - 5) / (EXPLICIT_YEARS - 5)
        prev = crev
        crev = prev * (1 + g_yr)
        proj_ebit = crev * ebit_m
        nopat = proj_ebit * (1 - tax)
        proj_da = crev * da_p
        proj_capex = crev * capex_p
        delta_nwc = (crev - prev) * nwc_p
        fcff = nopat + proj_da - proj_capex - delta_nwc
        pv = fcff / ((1 + wacc) ** yr)
        pv_tot += pv
        rows.append({
            "Year": f"Year {yr}",
            "Revenue": crev,
            "EBIT": proj_ebit,
            "NOPAT": nopat,
            "D&A": proj_da,
            "CapEx": proj_capex,
            "Delta NWC": delta_nwc,
            "FCFF": fcff,
            "PV of FCFF": pv,
        })

    tv = (rows[-1]["FCFF"] * (1 + terminal_g)) / (wacc - terminal_g)
    pv_tv = tv / ((1 + wacc) ** EXPLICIT_YEARS)
    ev = pv_tot + pv_tv
    eq_val = ev - debt + cash
    intrinsic = eq_val / shares
    upside = ((intrinsic - price) / price) * 100
    mos_buy = intrinsic * (1 - mos_pct)
    if intrinsic <= 0 and not_meaningful_reason is None:
        not_meaningful_reason = "Model value is negative: debt exceeds projected cash flows"

    return {
        "valid": True,
        "model": "FCFF DCF",
        "is_financial": False,
        "meaningful": not_meaningful_reason is None,
        "not_meaningful_reason": not_meaningful_reason,
        "history_years": rev_years,
        "sector": sector,
        "currency": info.get("currency", "INR"),
        "price": price,
        "shares": shares,
        "base_revenue": rev,
        "hist_driver": hist_cagr,
        "driver": rev_g,
        "driver_label": "Rev Growth",
        "ebit_margin": ebit_m,
        "tax_rate": tax,
        "da_pct": da_p,
        "capex_pct": capex_p,
        "nwc_pct": nwc_p,
        "discount_rate": wacc,
        "terminal_g": terminal_g,
        "pv_fcff_total": pv_tot,
        "tv": tv,
        "pv_tv": pv_tv,
        "enterprise_value": ev,
        "equity_value": eq_val,
        "total_debt": debt,
        "cash": cash,
        "fcf_ttm": fcf_ttm,
        "dividends_paid": divs_paid,
        "ebitda_ttm": ebitda_ttm,
        "inputs": inputs.as_dict(),
        "intrinsic_price": intrinsic,
        "mos_buy_price": mos_buy,
        "upside_pct": upside,
        "projection_df": pd.DataFrame(rows),
    }


SCENARIO_SHIFTS = {
    # non-financials: growth shift, margin multiplier, discount shift
    "bear": {"growth": -0.04, "margin": 0.85, "disc": 0.01, "roe": -0.03},
    "bull": {"growth": 0.04, "margin": 1.10, "disc": -0.01, "roe": 0.03},
}

MIN_DISCOUNT_SPREAD = 0.02  # scenario discount rates stay at least 2pp above terminal growth

KEY_INPUTS = {
    False: ("revenue_growth", "ebit_margin", "tax_rate", "beta", "da_pct", "capex_pct"),
    True: ("roe", "beta", "payout", "bvps"),
}


def compute_scenarios(bundle: dict, macro: dict) -> dict:
    """Bear / base / bull per-share values. Values are None when the model can't run."""
    kw = dict(rf=macro["rf"], erp=macro["erp"], terminal_g=macro["terminal_g"], mos_pct=macro["mos_pct"])
    base = compute_valuation(bundle, **kw)
    out = {"bear": None, "base": None, "bull": None, "base_result": base, "unstable_reason": None}
    if not base.get("valid"):
        return out
    out["base"] = base["intrinsic_price"]
    min_disc = macro["terminal_g"] + MIN_DISCOUNT_SPREAD
    if base["discount_rate"] < min_disc:
        out["unstable_reason"] = "Discount rate too close to long-term growth: value unreliable"
    for name, s in SCENARIO_SHIFTS.items():
        disc = max(base["discount_rate"] + s["disc"], min_disc)
        if base["is_financial"]:
            r = compute_valuation(bundle, **kw, driver_override=base["driver"] + s["roe"], discount_override=disc)
        else:
            r = compute_valuation(bundle, **kw, driver_override=base["driver"] + s["growth"],
                                  margin_override=base["ebit_margin"] * s["margin"], discount_override=disc)
        out[name] = r["intrinsic_price"] if r.get("valid") else None
    if out["unstable_reason"] is None and (out["bear"] is None or out["bull"] is None or out["bear"] <= 0):
        out["unstable_reason"] = "Bear-case value is negative: valuation too sensitive to assumptions"
    return out


def verdict(price: float, scenarios: dict, meaningful: bool) -> str:
    """Cheap below the bear value, Expensive above the bull value, otherwise Fair."""
    bear, base, bull = scenarios.get("bear"), scenarios.get("base"), scenarios.get("bull")
    if not meaningful or bear is None or base is None or bull is None:
        return "Not rated"
    if price < bear:
        return "Cheap"
    if price > bull:
        return "Expensive"
    return "Fair"


def confidence(inputs: dict, meaningful: bool) -> str:
    """High / Medium / Low depending on how many key inputs were guessed rather than reported."""
    if not meaningful:
        return "Low"
    is_fin = "roe" in inputs
    statuses = [inputs.get(k, {"status": "default"})["status"] for k in KEY_INPUTS[is_fin]]
    defaults = statuses.count("default")
    estimated = statuses.count("estimated")
    if defaults >= 2:
        return "Low"
    if defaults == 1 or estimated >= 2:
        return "Medium"
    return "High"


def simulate_values(val: dict, terminal_g: float, n: int = 5000, seed: int = 42, noise: float = 1.0) -> np.ndarray:
    """Monte Carlo of per-share value using the same model as compute_valuation.

    Randomises the driver, margin (non-financials) and discount rate around `val`'s base values.
    noise=0 reproduces val["intrinsic_price"] exactly.
    """
    rng = np.random.default_rng(seed)
    disc = np.maximum(rng.normal(val["discount_rate"], 0.01 * noise, n), terminal_g + 0.01)
    if val["is_financial"]:
        roe = np.clip(rng.normal(val["driver"], 0.02 * noise, n), 0.04, 0.35) if noise else np.full(n, val["driver"])
        bv = np.full(n, val["bvps"], dtype=float)
        pv_er = np.zeros(n)
        for yr in range(1, 6):
            pv_er += bv * (roe - disc) / ((1 + disc) ** yr)
            bv = bv + bv * roe * (1 - val["payout_ratio_model"])
        tv = bv * (roe - disc) / (1 + disc - ER_PERSISTENCE)
        return val["bvps"] + pv_er + tv / ((1 + disc) ** 5)

    g0 = rng.normal(val["driver"], 0.03 * noise, n)
    margin = np.clip(rng.normal(val["ebit_margin"], 0.02 * noise, n), 0.01, 0.65) if noise else np.full(n, val["ebit_margin"])
    crev = np.full(n, val["base_revenue"], dtype=float)
    pv_tot = np.zeros(n)
    for yr in range(1, EXPLICIT_YEARS + 1):
        g_yr = g0 if yr <= 5 else g0 + (terminal_g - g0) * (yr - 5) / (EXPLICIT_YEARS - 5)
        prev = crev
        crev = prev * (1 + g_yr)
        fcff = (crev * margin * (1 - val["tax_rate"]) + crev * (val["da_pct"] - val["capex_pct"])
                - (crev - prev) * val["nwc_pct"])
        pv_tot += fcff / ((1 + disc) ** yr)
    tv = fcff * (1 + terminal_g) / (disc - terminal_g)
    ev = pv_tot + tv / ((1 + disc) ** EXPLICIT_YEARS)
    return (ev - val["total_debt"] + val["cash"]) / val["shares"]


REVERSE_LOW, REVERSE_HIGH, REVERSE_STEP = -0.25, 0.70, 0.05


def solve_reverse_valuation(bundle: dict, discount_rate: float, terminal_g: float = 0.05) -> dict:
    """
    Reverse DCF / Reverse Excess Return: the growth (non-financials) or ROE (financials), in %,
    that makes model value equal today's price.

    Returns {"implied": float | None, "status": "ok" | "above_range" | "below_range" | "invalid"}.
    """
    def diff(driver_val):
        r = compute_valuation(bundle, terminal_g=terminal_g, driver_override=driver_val,
                              discount_override=discount_rate)
        if not r.get("valid"):
            return None
        return r["intrinsic_price"] - r["price"]

    grid = np.round(np.arange(REVERSE_LOW, REVERSE_HIGH + 1e-9, REVERSE_STEP), 4)
    points = [(float(x), diff(float(x))) for x in grid]
    points = [(x, d) for x, d in points if d is not None and np.isfinite(d)]
    if not points:
        return {"implied": None, "status": "invalid"}
    for (x0, d0), (x1, d1) in zip(points, points[1:]):
        if d0 == 0:
            return {"implied": round(x0 * 100, 1), "status": "ok"}
        if d0 * d1 < 0:
            try:
                root = brentq(lambda v: diff(v) or 0.0, x0, x1, xtol=1e-6)
                return {"implied": round(root * 100, 1), "status": "ok"}
            except (ValueError, RuntimeError):
                return {"implied": None, "status": "invalid"}
    if points[-1][1] == 0:
        return {"implied": round(points[-1][0] * 100, 1), "status": "ok"}
    # No crossing: price is above every model value, or below every model value.
    if all(d < 0 for _, d in points):
        return {"implied": None, "status": "above_range"}
    return {"implied": None, "status": "below_range"}


